/**
 * Reads a CSV (exported from Macadamia Kernel Statistics Excel) and outputs
 * SQL that calls import_historical_kernel_batch for each row. Run the SQL
 * in Supabase (MCP execute_sql or SQL Editor) to load historical kernel data.
 *
 * Usage:
 *   node scripts/import-historical-kernel-from-csv.js < data.csv
 *   node scripts/import-historical-kernel-from-csv.js path/to/data.csv
 *
 * Required CSV columns (header row; names are case-insensitive, spaces trimmed):
 *   Batch (or Batch Number, BatchNumber) — required
 *   Grower (or Supplier, Grower Name) — optional
 *   Received Date (or ReceivedDate) — optional, format YYYY-MM-DD or DD/MM/YYYY
 *   Finished Date (or Production Finished, FinishedDate) — optional
 *   SP, 0, 1, 1S, 4L, 5, 6, 7/8, B.High, B.Low — yield in kg (optional; default 0)
 *   Wet NIS kg (optional), Best Before (optional), FFA (optional)
 */

const fs = require('fs');
const path = require('path');

function parseCsvLine(line) {
    const out = [];
    let cur = '';
    let inQuotes = false;
    for (let i = 0; i < line.length; i++) {
        const c = line[i];
        if (c === '"') {
            inQuotes = !inQuotes;
        } else if ((c === ',' && !inQuotes) || (c === '\t' && !inQuotes)) {
            out.push(cur.trim());
            cur = '';
        } else {
            cur += c;
        }
    }
    out.push(cur.trim());
    return out;
}

function parseDate(s) {
    if (s == null || String(s).trim() === '') return null;
    s = String(s).trim();
    const d = s.match(/^(\d{4})-(\d{2})-(\d{2})$/);
    if (d) return `${d[1]}-${d[2]}-${d[3]}`;
    const d2 = s.match(/^(\d{1,2})[\/\-](\d{1,2})[\/\-](\d{2,4})$/);
    if (d2) {
        const day = d2[1].padStart(2, '0');
        const month = d2[2].padStart(2, '0');
        const year = d2[3].length === 2 ? '20' + d2[3] : d2[3];
        return `${year}-${month}-${day}`;
    }
    return null;
}

function num(v) {
    if (v == null || String(v).trim() === '') return 0;
    const n = parseFloat(String(v).replace(/,/g, ''));
    return isNaN(n) ? 0 : n;
}

function escapeSql(v) {
    if (v == null || v === '') return 'NULL';
    return "'" + String(v).replace(/'/g, "''") + "'";
}

function findCol(headers, ...names) {
    const h = headers.map(h => (h || '').toLowerCase().trim());
    for (const n of names) {
        const idx = h.indexOf(n.toLowerCase().trim());
        if (idx !== -1) return idx;
    }
    return -1;
}

function main() {
    let input;
    const fileArg = process.argv[2];
    if (fileArg && fs.existsSync(fileArg)) {
        input = fs.readFileSync(fileArg, 'utf8');
    } else {
        input = fs.readFileSync(0, 'utf8');
    }

    const lines = input.split(/\r?\n/).filter(l => l.length > 0);
    if (lines.length < 2) {
        console.error('CSV needs a header row and at least one data row.');
        process.exit(1);
    }

    const headers = parseCsvLine(lines[0]);
    const batchCol = findCol(headers, 'batch', 'batch number', 'batchnumber', 'batch_number');
    if (batchCol === -1) {
        console.error('CSV must have a column named Batch (or Batch Number). Headers:', headers.join(', '));
        process.exit(1);
    }

    const growerCol = findCol(headers, 'grower', 'supplier', 'grower name', 'growername');
    const receivedCol = findCol(headers, 'received date', 'receiveddate', 'received');
    const finishedCol = findCol(headers, 'finished date', 'production finished', 'finisheddate', 'finished', 'completion date');
    const wetCol = findCol(headers, 'wet nis kg', 'wet nis', 'wet_nis_kg');
    const bestBeforeCol = findCol(headers, 'best before', 'bestbefore', 'bb date', 'bb_date');
    const ffaCol = findCol(headers, 'ffa');

    const styleCols = {
        sk_sp_qty: findCol(headers, 'sp', 'sk sp'),
        sk_0_qty: findCol(headers, '0'),
        sk_1_qty: findCol(headers, '1'),
        sk_1s_qty: findCol(headers, '1s'),
        sk_4l_qty: findCol(headers, '4l'),
        sk_5_qty: findCol(headers, '5'),
        sk_6_qty: findCol(headers, '6'),
        bt_78_qty: findCol(headers, '7/8', '78', '7/8 qty'),
        bt_high_qty: findCol(headers, 'b.high', 'b high', 'butter high', 'butter high oil'),
        bt_low_qty: findCol(headers, 'b.low', 'b low', 'butter low', 'butter low oil')
    };

    console.log('-- Generated by scripts/import-historical-kernel-from-csv.js');
    console.log('-- Run this SQL in Supabase (MCP execute_sql or SQL Editor).');
    console.log('');

    for (let i = 1; i < lines.length; i++) {
        const cells = parseCsvLine(lines[i]);
        const batchNumber = (cells[batchCol] || '').trim();
        if (!batchNumber) continue;

        const grower = growerCol >= 0 ? (cells[growerCol] || '').trim() || null : null;
        const receivedDate = receivedCol >= 0 ? parseDate(cells[receivedCol]) : null;
        const finishedDate = finishedCol >= 0 ? parseDate(cells[finishedCol]) : receivedDate;
        const wetNis = wetCol >= 0 ? num(cells[wetCol]) : null;
        const bestBefore = bestBeforeCol >= 0 ? parseDate(cells[bestBeforeCol]) : null;
        const ffa = ffaCol >= 0 ? num(cells[ffaCol]) : null;

        const sk_sp = styleCols.sk_sp_qty >= 0 ? num(cells[styleCols.sk_sp_qty]) : 0;
        const sk_0 = styleCols.sk_0_qty >= 0 ? num(cells[styleCols.sk_0_qty]) : 0;
        const sk_1 = styleCols.sk_1_qty >= 0 ? num(cells[styleCols.sk_1_qty]) : 0;
        const sk_1s = styleCols.sk_1s_qty >= 0 ? num(cells[styleCols.sk_1s_qty]) : 0;
        const sk_4l = styleCols.sk_4l_qty >= 0 ? num(cells[styleCols.sk_4l_qty]) : 0;
        const sk_5 = styleCols.sk_5_qty >= 0 ? num(cells[styleCols.sk_5_qty]) : 0;
        const sk_6 = styleCols.sk_6_qty >= 0 ? num(cells[styleCols.sk_6_qty]) : 0;
        const bt_78 = styleCols.bt_78_qty >= 0 ? num(cells[styleCols.bt_78_qty]) : 0;
        const bt_high = styleCols.bt_high_qty >= 0 ? num(cells[styleCols.bt_high_qty]) : 0;
        const bt_low = styleCols.bt_low_qty >= 0 ? num(cells[styleCols.bt_low_qty]) : 0;

        const recDate = receivedDate ? escapeSql(receivedDate) : 'NULL';
        const finDate = finishedDate ? escapeSql(finishedDate + ' 12:00:00') : 'NULL';
        const wetVal = wetNis != null && !isNaN(wetNis) ? wetNis : 'NULL';
        const bbVal = bestBefore ? escapeSql(bestBefore) : 'NULL';
        const ffaVal = ffa != null && !isNaN(ffa) ? ffa : 'NULL';

        const sql = `SELECT import_historical_kernel_batch(
  ${escapeSql(batchNumber)},
  ${grower != null ? escapeSql(grower) : 'NULL'},
  NULL,
  ${recDate},
  ${finDate},
  ${wetVal},
  ${sk_sp}, ${sk_0}, ${sk_1}, ${sk_1s}, ${sk_4l}, ${sk_5}, ${sk_6}, ${bt_78}, ${bt_high}, ${bt_low},
  ${bbVal},
  ${ffaVal}
);`;
        console.log(sql);
        console.log('');
    }
}

main();
