#!/usr/bin/env node
/**
 * Sync WebPortal/js/appRouteConfig.json (and js/appRouteConfig.json) from supabase/projects.json.
 * Also regenerates WebPortal/js/macavation-supabase.js (sign-in bootstrap).
 *
 * There are exactly two database targets:
 *   prod — only ever served to hosts in PROD_HOSTS
 *   dev  — everything else (localhost, dev site, unknown hosts)
 *
 * Usage:
 *   node scripts/sync-portal-supabase-config.mjs
 *   npm run supabase:sync-portal
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import {
  PRODUCTION,
  DEV,
  BLOCKED_PROJECT_REFS,
  anonKeyMatchesProject,
} from './lib/supabase-projects.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');

// Hosts that may resolve to the production database. Must stay in sync with
// getEnvironment() in js/appRouter.js and WebPortal/js/appRouter.js.
const PROD_HOSTS = ['macavation.customapp.org', 'macavation.customapp.co.za'];

const PROD_LAMBDA =
  PRODUCTION.lambdaProxyUrl ||
  'https://rzrx6ntfejvb6lxpmt4ywruvt40mjjuo.lambda-url.af-south-1.on.aws/proxy/function';

function resolveDevLambda() {
  const configured = (DEV.lambdaProxyUrl || '').trim();
  if (configured) return configured;
  console.warn(
    'WARN: dev.lambdaProxyUrl is empty in supabase/projects.json.\n' +
      '      Dev portal environments will use the production Lambda until a dev Lambda is deployed.\n' +
      '      See docs/setup/UAT_DATABASE.md → Lambda proxy.'
  );
  return PROD_LAMBDA;
}

function buildEnvSettings() {
  if (!DEV.anonKey || !anonKeyMatchesProject(DEV.anonKey, DEV.ref)) {
    console.error(
      'Dev anon key missing or does not match project ref in supabase/projects.json.\n' +
        'Add the anon (or publishable) key from Supabase Dashboard → Macavation Dev → Settings → API, then re-run.'
    );
    process.exit(1);
  }

  const devLambda = resolveDevLambda();

  const prod = {
    SupabaseUrl: PRODUCTION.apiUrl,
    SupabaseAnonKey: PRODUCTION.anonKey,
    LambdaProxyUrl: PROD_LAMBDA,
  };
  const dev = {
    SupabaseUrl: DEV.apiUrl,
    SupabaseAnonKey: DEV.anonKey,
    LambdaProxyUrl: devLambda,
  };

  // default is dev on purpose: a missing/unknown environment key must never
  // fall back to production. demo is dev for the same reason.
  return {
    default: dev,
    dev,
    demo: dev,
    prod,
  };
}

function patchRouteConfig(relPath) {
  const abs = path.join(root, relPath);
  if (!fs.existsSync(abs)) return;
  const json = JSON.parse(fs.readFileSync(abs, 'utf8'));
  json.environmentSettings = buildEnvSettings();
  fs.writeFileSync(abs, JSON.stringify(json, null, 4) + '\n', 'utf8');
  console.log(`Updated ${relPath}`);
}

function writeMacavationSupabaseJs() {
  const devLambda = resolveDevLambda();
  const content = `/**
 * Canonical Supabase settings for the Web Portal sign-in bootstrap.
 * Generated by npm run supabase:sync-portal — do not edit by hand.
 *
 * Settings are chosen by hostname at runtime: only PROD_HOSTS get the
 * production database; every other host (localhost, dev, unknown) gets dev.
 */
(function (global) {
    'use strict';

    var PROD_HOSTS = ${JSON.stringify(PROD_HOSTS)};

    var PROD = {
        projectRef: '${PRODUCTION.ref}',
        url: '${PRODUCTION.apiUrl}',
        anonKey: '${PRODUCTION.anonKey}',
        lambdaProxyUrl: '${PROD_LAMBDA}'
    };
    var DEV = {
        projectRef: '${DEV.ref}',
        url: '${DEV.apiUrl}',
        anonKey: '${DEV.anonKey}',
        lambdaProxyUrl: '${devLambda}'
    };

    var host = '';
    if (typeof location !== 'undefined' && location && location.hostname) {
        host = String(location.hostname).toLowerCase();
    }
    var settings = PROD_HOSTS.indexOf(host) > -1 ? PROD : DEV;

    var BLOCKED_REFS = ${JSON.stringify(BLOCKED_PROJECT_REFS)};
    var ALLOWED_REFS = ${JSON.stringify([PRODUCTION.ref, DEV.ref])};

    function assertAllowedSupabaseUrl(url) {
        var u = String(url || '');
        if (!u) {
            return;
        }
        var i;
        for (i = 0; i < BLOCKED_REFS.length; i++) {
            if (u.indexOf(BLOCKED_REFS[i]) >= 0) {
                throw new Error('Supabase URL points at a blocked project (' + BLOCKED_REFS[i] + ').');
            }
        }
        var allowed = false;
        for (i = 0; i < ALLOWED_REFS.length; i++) {
            if (u.indexOf(ALLOWED_REFS[i]) >= 0) {
                allowed = true;
                break;
            }
        }
        if (!allowed) {
            throw new Error('Supabase URL must target Macavation production or dev, not: ' + u);
        }
    }

    /** @deprecated use assertAllowedSupabaseUrl */
    function assertMacavationSupabaseUrl(url) {
        assertAllowedSupabaseUrl(url);
    }

    function getLambdaBaseUrl() {
        return String(settings.lambdaProxyUrl || '').replace(/\\/proxy\\/function$/, '');
    }

    global.MACAVATION_SUPABASE = {
        projectRef: settings.projectRef,
        url: settings.url,
        anonKey: settings.anonKey,
        lambdaProxyUrl: settings.lambdaProxyUrl,
        getLambdaBaseUrl: getLambdaBaseUrl,
        assertAllowedSupabaseUrl: assertAllowedSupabaseUrl,
        assertMacavationSupabaseUrl: assertMacavationSupabaseUrl
    };
}(typeof window !== 'undefined' ? window : globalThis));
`;
  const out = path.join(root, 'WebPortal/js/macavation-supabase.js');
  fs.writeFileSync(out, content, 'utf8');
  console.log('Updated WebPortal/js/macavation-supabase.js');
}

patchRouteConfig('WebPortal/js/appRouteConfig.json');
patchRouteConfig('js/appRouteConfig.json');
writeMacavationSupabaseJs();
