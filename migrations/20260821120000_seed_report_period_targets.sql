-- Backfill report_period_targets from Pete's own report sheets.
--
-- report_period_targets has been EMPTY since it was created (20260817100000). Every Target column
-- and every Achieved % in every report therefore renders blank, which makes the whole
-- Achieved-vs-Target framing of the report inert.
--
-- WHY THE REPORT SHEETS AND NOT THE FORECAST WORKBOOKS
-- ---------------------------------------------------
-- "Sales Forecast 2027 FYE.xlsx" and "Production, Sales and Procurement forecast.xlsx" are the
-- planning inputs, and they do NOT reproduce the targets Pete actually reported against. For July
-- 2026 the forecast implies a monthly EVMO sales target of R310,921.88 (3,731,062.50 / 12) while his
-- report states R412,500.00; the forecast's crude line implies R3,264,456.25 against his
-- R3,189,587.50. Seeding from the forecast would silently restate the target on periods already
-- issued to directors.
--
-- A target is a fact about ONE period — which is exactly what report_period_targets models, and why
-- upsert_report_period_target refuses to touch any other period. The authoritative record of what
-- target applied to a given week or month is the sheet that reported it. So this backfill reads the
-- Target column out of the 63 report sheets, and the forecast workbooks stay what they are:
-- planning inputs for FUTURE targets, which Pete sets through the existing UI.
--
-- VERIFICATION
-- ------------
-- Every extracted July 2026 monthly target was checked against the "July Report" sheet by hand:
--   Nut in Shell Cracking 100,000    Sound Kernel Packing 17,500    Kernel Sales 1,933,578.67
--   Cosmetic Oil 60,000    EV Oil 10,000    Cake Produced 36,000    Protein Produced 1,500
--   Protein + Crispies 220,000    Extra Virgin 412,500    Crude Cosmetic 3,189,587.50    Cake 200,000
-- and the weekly "27-31 July" sheet: Cracking 25,000, Packing 4,375, Cosmetic 15,000, EVMO 2,500,
-- Cake 10,000. All matched exactly.
--
-- WHAT WAS DROPPED, AND WHY
-- -------------------------
-- 6 rows from June Week 3, June Week 4 carry a year of 2206 — a transposition typo in the source
-- sheet's own Start Date cell. Rather than guess which 2026 week was meant (the corrected date is
-- mid-week, so the Monday it normalises to is ambiguous and could collide with a real sheet), those
-- rows are excluded. They are the standard recurring weekly targets (25,000 / 4,375 / 15,000) and
-- Pete can set them in the UI in seconds. Silently inventing a period is the one thing not done here.
--
-- 359 targets are loaded: 104 monthly and 255 weekly.
--
-- IDEMPOTENT AND NON-DESTRUCTIVE: ON CONFLICT DO NOTHING, so a target a human has already set is
-- never overwritten by this backfill, however many times it runs. set_by stays NULL — no human set
-- these — and notes records the sheet each came from so any figure can be traced back.
--
