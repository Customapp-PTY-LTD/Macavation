       'Backfilled from Macavation Weekly and Monthly Reports.xlsx (' || i.source_sheet || ')',
       NULL
FROM incoming i
JOIN public.report_metrics m ON m.metric_key = i.metric_key
-- Only where the metric actually offers that period type. A weekly target on a monthly-only metric
-- would be dead data that no report can ever read.
WHERE i.period_type = ANY (m.period_types)
  -- Guard the table's own contract: period_start must be the canonical period start.
  AND i.period_start = public.report_normalise_period_start(i.period_type, i.period_start)
ON CONFLICT (metric_key, period_type, period_start) DO NOTHING;

